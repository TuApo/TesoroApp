/**
 * Empresa usuaria (normalizada) -> código de compañía de nómina.
 *
 * Sale de `FICHA V12!I94` de BASE CONTRATACIÓN, que lo resuelve con SUBSTITUTE
 * encadenados sobre el nombre de la empresa. Allá los códigos están escritos
 * con la letra O ("OO1", "O11"); aquí se normalizan a dígito 0, que es lo
 * coherente con que "O11"/"O12" lleven una sola.
 *
 * Las empresas que no estén aquí devuelven '' a propósito: el Excel, al no
 * encontrar la empresa, deja pasar el nombre completo como si fuera el código,
 * y eso no puede llegar a nómina.
 */
export const CODIGO_COMPANIA_POR_EMPRESA: Record<string, string> = {
  'EXCELLENCE FLOWERS': '012',
  'FANTASY FLOWERS': '004',
  'MERCEDES': '005',
  'THE ELITE FLOWER': '001',
  'WAYUU FLOWERS': '011',
};

/** Centro de costo que no se resuelve por cargo sino con área fija. */
const AREA_FIJA_POR_CENTRO: Array<{ patron: RegExp; area: string }> = [
  { patron: /LAS\s+DELICIAS/i, area: 'DEL' },
];

const LABORES_POR_JUEGO: Record<JuegoLabores, Record<string, string>> = {
  APOYO: LABOR_POR_MES_AREA_APOYO,
  BLU: LABOR_POR_MES_AREA_BLU,
  ALIANZA: LABOR_POR_MES_AREA_ALIANZA,
};

const CARGOS_POR_JUEGO: Record<JuegoLabores, Record<string, string>> = {
  APOYO: AREA_POR_CARGO_APOYO,
  BLU: AREA_POR_CARGO_APOYO,
  ALIANZA: AREA_POR_CARGO_ALIANZA,
};

/** Mayúsculas sin acentos ni puntuación, para comparar nombres de empresa. */
function normalizarEmpresa(v: string | null | undefined): string {
  return String(v ?? '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/\bEN\s+REORGANIZACION\b/g, ' ')
    .replace(/\b(S\.?A\.?S\.?|S\.?A\.?|LTDA\.?|C\.?I\.?|E\.?U\.?|SCA)\b/g, ' ')
    .replace(/[^A-Z0-9 ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Decide de qué hoja sale la labor.
 *
 * Elite Blu se mira ANTES que la temporal a propósito: en el maestro sus 10
 * filas tienen `temporal = 'Apoyo Laboral TS'`, así que por temporal caería en
 * el juego de Apoyo y le pondría labores de rosas a una finca de arándanos.
 */
export function juegoDeLabores(
  temporal?: string | null,
  empresa?: string | null,
): JuegoLabores {
  if (/ELITE\s*BLU/i.test(normalizarEmpresa(empresa))) return 'BLU';
  const t = normalizarEmpresa(temporal);
  if (/ALIANZA/.test(t)) return 'ALIANZA';
  return 'APOYO';
}

/** Código de compañía de nómina, o '' si la empresa no tiene uno asignado. */
export function resolverCodigoCompania(empresa: string | null | undefined): string {
  const n = normalizarEmpresa(empresa);
  if (!n) return '';
  if (CODIGO_COMPANIA_POR_EMPRESA[n]) return CODIGO_COMPANIA_POR_EMPRESA[n];
  // "THE ELITE FLOWER C I" contra la clave "THE ELITE FLOWER": basta con que
  // el nombre del maestro empiece por la clave.
  const clave = Object.keys(CODIGO_COMPANIA_POR_EMPRESA).find(k => n.startsWith(k));
  return clave ? CODIGO_COMPANIA_POR_EMPRESA[clave] : '';
}

/** Código de área de un cargo dentro de un juego de labores. */
export function areaDeCargo(
  cargo: string | null | undefined,
  juego: JuegoLabores = 'APOYO',
): string | null {
  const c = String(cargo ?? '').trim().toUpperCase().replace(/\s+/g, ' ');
  if (!c) return null;
  return CARGOS_POR_JUEGO[juego][c] ?? AREA_POR_CARGO_APOYO[c] ?? null;
}

/**
 * Devuelve la descripción de la obra, o `null` si no hay labor definida para
 * esa combinación.
 *
 * Reproduce la fórmula de la base de contratación:
 *
 *   descripcion = VLOOKUP( MONTH(fechaIngreso) & area , 'LABORES POR MES'!C:D )
 *   donde  area = VLOOKUP(cargo, <maestro de cargos>)
 *   salvo el centro de costo LAS DELICIAS, que usa el área fija 'DEL'.
 *
 * Devuelve `null` —y no un texto cualquiera— cuando el área del cargo no existe
 * en la hoja que aplica. Pasa de verdad: los 30 cargos de jardinería de Tu
 * Alianza son área `JAR` y esa hoja solo define 7 áreas, ninguna es `JAR`.
 *
 * @param cargo        Cargo del candidato (se compara en mayúsculas).
 * @param fechaIngreso Fecha de ingreso; de ella solo se usa el mes.
 * @param centroCosto  Empresa usuaria / centro de costo, para las excepciones.
 * @param temporal     Temporal de la vacante (Apoyo / Tu Alianza).
 * @param empresa      Empresa usuaria, para detectar Elite Blu.
 */
export function resolverDescripcionObra(
  cargo: string | null | undefined,
  fechaIngreso: Date | string | null | undefined,
  centroCosto?: string | null,
  temporal?: string | null,
  empresa?: string | null,
): string | null {
  const mes = mesDe(fechaIngreso);
  if (!mes) return null;

  const juego = juegoDeLabores(temporal, empresa ?? centroCosto);

  const centro = String(centroCosto ?? '');
  const fija = AREA_FIJA_POR_CENTRO.find(x => x.patron.test(centro));

  const area = fija?.area ?? areaDeCargo(cargo, juego);
  if (!area) return null;

  return LABORES_POR_JUEGO[juego][`${mes}${area}`] ?? null;
}

/**
 * Mes (1-12) de una fecha, o `null` si no hay o no es válida.
 *
 * `new Date('2026-08-01')` se interpreta como MEDIANOCHE UTC, que en Colombia
 * (UTC-5) es el 31 de julio: `getMonth()` devolvería julio y la obra saldría del
 * mes anterior justo en los cambios de mes, que es cuando más se nota. Por eso
 * las cadenas `YYYY-MM-DD` se leen a mano en vez de con `new Date()`.
 */
export function mesDe(fecha: Date | string | null | undefined): number | null {
  if (!fecha) return null;

  if (fecha instanceof Date) {
    return isNaN(fecha.getTime()) ? null : fecha.getMonth() + 1;
  }

  const s = String(fecha).trim();
  const ymd = /^(\d{4})-(\d{2})-(\d{2})/.exec(s);
  if (ymd) {
    const mes = Number(ymd[2]);
    return mes >= 1 && mes <= 12 ? mes : null;
  }

  const d = new Date(s);
  return isNaN(d.getTime()) ? null : d.getMonth() + 1;
}

/**
 * Fecha con la que la VACANTE calcula su descripción, por orden de preferencia:
 *
 *   1. Fecha de ingreso     — solo existe en "Contratación inmediata".
 *   2. Fecha de prueba téc. — es la que se conoce al publicar, y la persona
 *                             suele entrar el mismo mes o el siguiente.
 *   3. Fecha de publicación — último recurso.
 *
 * La de publicación va de última porque es "hoy": una vacante que se publica el
 * 5 de agosto para una prueba del 11 de julio daría la obra de agosto teniendo
 * la de julio a la mano.
 *
 * Es una aproximación a propósito. La definitiva es la fecha de ingreso de la
 * pantalla de contratación, que es la que va al contrato.
 */
export function fechaParaDescripcionVacante(
  fechaIngreso: Date | string | null | undefined,
  fechaPruebaTecnica: Date | string | null | undefined,
  fecha_publicado: Date | string | null | undefined,
): Date | string | null {
  return fechaIngreso || fechaPruebaTecnica || fecha_publicado || null;
}

/**
 * Descompone el prefijo de una descripción generada: "8PO APOYO…" -> mes 8,
 * área "PO". Devuelve `null` si el texto no tiene esa forma (redactado a mano).
 */
export function claveDescripcion(
  texto: string | null | undefined,
): { mes: number; area: string } | null {
  const m = /^(\d{1,2})([A-Z]{2,3})\s/.exec(String(texto ?? '').trim());
  if (!m) return null;
  const mes = Number(m[1]);
  if (mes < 1 || mes > 12) return null;
  return { mes, area: m[2] };
}

/** `true` si el texto es una descripción generada por estas tablas. */
export function esDescripcionGenerada(texto: string | null | undefined): boolean {
  const t = String(texto ?? '').trim();
  if (!t) return false;
  return Object.values(LABORES_POR_JUEGO).some(tabla =>
    Object.values(tabla).some(v => v === t),
  );
}

/**
 * `true` si la descripción quedó de otro mes distinto al de la fecha de ingreso.
 *
 * Es el caso que se da todo el tiempo: la vacante se publica con la fecha de
 * prueba técnica (p. ej. 28 de julio) y la persona termina ingresando el 3 de
 * agosto. La obra que se imprime en el contrato tiene que ser la de agosto.
 */
export function descripcionEsDeOtroMes(
  texto: string | null | undefined,
  fechaIngreso: Date | string | null | undefined,
): boolean {
  const mes = mesDe(fechaIngreso);
  const clave = claveDescripcion(texto);
  if (!mes || !clave) return false;
  return clave.mes !== mes;
}
