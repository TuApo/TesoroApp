/**
 * Catálogo de labores por mes y de áreas por cargo.
 *
 * Transcrito de `CENTROS DE COSTO APOYO Y  ALIANZA V2.xlsx`:
 *
 *   - LABORES POR MES APOYO      col C (EQ) -> col D (Labor)   216 filas
 *   - LABORES POR MES BLU        col C (EQ) -> col D (Labor)   132 filas
 *   - LABORES POR MES TU ALIANZA col C (EQ) -> col D (Labor)   84 filas
 *   - CENTROS DE COSTO APOYO     col K (Cargos) -> col L (AREA)   86 cargos
 *   - CENTROS DE COSTO ALIANZA   col H (CARGOS) -> col I (AREA)   129 cargos
 *
 * En el Excel la columna D es una fórmula: `=+A&B&" "&UPPER(E)`, es decir
 * `mes & area & " " & labor en mayúsculas`. La clave de búsqueda (col C) es
 * `=+A&B` = `mes & area`. Aquí se guarda ya calculada.
 *
 * Los datos viven en el código y no en el Excel para que al sacar versión no
 * dependamos de un archivo externo. Si en la base cambian las labores del año,
 * hay que volver a generar este archivo.
 */

